#!/bin/bash
set -euo pipefail

# Cloudflare origin lock — podiumclass.online
# Restricts HTTP/HTTPS (80/443) to Cloudflare edge IPs only, once the domain is
# proxied. Run this on the VPS AFTER the nameservers have switched to Cloudflare
# and the site resolves through it. SSH, LiveKit, and TURN ports are untouched.

SITE="podiumclass.online"
CF_V4_URL="https://www.cloudflare.com/ips-v4"
CF_V6_URL="https://www.cloudflare.com/ips-v6"

echo "→ Checking $SITE currently resolves through Cloudflare..."
if ! curl -fsSI --max-time 15 "https://$SITE" | grep -qi '^cf-ray:'; then
    echo "ABORT: $SITE is not behind Cloudflare yet (no cf-ray header)." >&2
    echo "       Switch the Namecheap nameservers to Cloudflare and wait for" >&2
    echo "       propagation first. Nothing was changed." >&2
    exit 1
fi
echo "   OK — site is proxied through Cloudflare."

CF_IPS=$(curl -fsS --max-time 20 "$CF_V4_URL")
CF_IPS6=$(curl -fsS --max-time 20 "$CF_V6_URL")
COUNT_V4=$(echo "$CF_IPS" | grep -c .)
COUNT_V6=$(echo "$CF_IPS6" | grep -c .)
echo "→ Loaded $COUNT_V4 IPv4 + $COUNT_V6 IPv6 Cloudflare edge ranges."

echo "→ Inserting Cloudflare allow rules for ports 80/443..."
for ip in $CF_IPS; do
    ufw insert 1 allow from "$ip" to any port 80 proto tcp >/dev/null
    ufw insert 1 allow from "$ip" to any port 443 proto tcp >/dev/null
done
for ip in $CF_IPS6; do
    ufw insert 1 allow from "$ip" to any port 80 proto tcp >/dev/null
    ufw insert 1 allow from "$ip" to any port 443 proto tcp >/dev/null
done

echo "→ Removing open-to-world 80/443 rules (direct-IP access now dropped)..."
for rule in "80/tcp" "80" "443/tcp" "443"; do
    ufw delete allow "$rule" >/dev/null 2>&1 || true
done

echo "→ Installing nginx real-IP config (logs see the real client, not Cloudflare)..."
{
    echo "# Real client IPs from Cloudflare (generated by cloudflare-lock.sh)"
    for ip in $CF_IPS; do
        echo "set_real_ip_from $ip;"
    done
    for ip in $CF_IPS6; do
        echo "set_real_ip_from $ip;"
    done
    echo "real_ip_header CF-Connecting-IP;"
} > /etc/nginx/conf.d/cloudflare-real-ip.conf

if nginx -t >/dev/null 2>&1; then
    systemctl reload nginx
    echo "   nginx reloaded."
else
    echo "WARNING: nginx config check failed — real-ip snippet kept but not loaded."
    echo "         Fix manually with: nginx -t && systemctl reload nginx"
fi

echo ""
echo "✅ Done. Summary:"
echo "   - 80/443 now accept only Cloudflare edge IPs; direct-IP access is dropped."
echo "   - SSH (22), LiveKit (7880/7881, 50000-60000/udp), TURN (3478/udp, 5349/tcp,"
echo "     40000-40100/udp) are unchanged."
echo "   - Rollback: ufw allow 80/tcp && ufw allow 443/tcp"
echo "     && rm /etc/nginx/conf.d/cloudflare-real-ip.conf && systemctl reload nginx"